#pragma once

#include "app_state.hpp"

#include <chrono>
#include <cstdint>
#include <cstdlib>

// Перегрузка входного тракта (клиппинг) — сколько отсчётов упёрлось в шкалу
// АЦП и какой был пик за окно наблюдения.
//
// Считается по сырым int16, до нормировки на 2048 и до калибровочного поворота
// Rx2: после умножения на комплексную поправку зажатый отсчёт уже не стоит
// ровно на шкале, и по float-значениям перегрузку было бы не отличить от
// просто громкого сигнала.
//
// Один и тот же класс кормят и поток захвата, и воспроизведение файла: у
// записи ровно та же беда, что у эфира, только увидеть её задним числом
// сложнее — сигнал уже испорчен, а усиление, при котором он записан, в файле
// не хранится.
class ClipMonitor {
public:
    // Шкала 12-битного АЦП AD9361: отсчёты приходят в диапазоне -2048..2047.
    static constexpr float kFullScale = 2048.0f;
    // Порог «отсчёт зажат» взят чуть ниже полной шкалы (-0.2 dBFS). Мы видим не
    // сам АЦП, а выход его дециматоров и FIR: после фильтрации срезанная
    // вершина почти никогда не попадает точно в код 2047, и счёт только точных
    // попаданий систематически недосчитывал бы реальную перегрузку.
    static constexpr int   kClipCode = 2000;

    explicit ClipMonitor(AppState& state) : state_(state) {}

    // Новый поток отсчётов (подключились к плате, запустили файл): счётчики и
    // история обнуляются, показания начинают жить.
    void begin();
    // Поток кончился: дописать недобранное окно и снять признак активности.
    void end();

    // Один отсчёт одноканального потока.
    inline void add(int16_t i1, int16_t q1) {
        accumulate(ch1_, i1, q1);
        ++samples_;
    }

    // Один отсчёт двухканального потока.
    inline void add(int16_t i1, int16_t q1, int16_t i2, int16_t q2) {
        accumulate(ch1_, i1, q1);
        accumulate(ch2_, i2, q2);
        dual_   = true;
        ++samples_;
    }

    // Вызывается раз в буфер/чанк; публикует статистику, когда набралось окно.
    // Публиковать чаще нет смысла (UI рисует 60 кадров в секунду), реже —
    // короткая пачка перегрузки размывается в доли процента и теряется.
    void tick();

private:
    struct Channel {
        uint64_t clipped { 0 };
        int      peak    { 0 };  // max(|I|,|Q|) за окно, в кодах АЦП
    };

    static inline void accumulate(Channel& c, int16_t i, int16_t q) {
        int ai = std::abs(static_cast<int>(i));
        int aq = std::abs(static_cast<int>(q));
        int m  = ai > aq ? ai : aq;
        if (m > c.peak) c.peak = m;
        if (m >= kClipCode) ++c.clipped;
    }

    void publish();
    void reset_stats();   // счётчики и история — при begin() и по запросу из UI

    AppState& state_;
    Channel   ch1_ {};
    Channel   ch2_ {};
    bool      dual_    { false };
    uint64_t  samples_ { 0 };      // отсчётов в текущем окне
    double    stream_time_s_ { 0.0 }; // время от начала потока, по числу отсчётов

    // Окно наблюдения ~100 мс. Считается по числу отсчётов, а не по часам:
    // воспроизведение файла идёт в темпе реального времени, но паузами между
    // чанками, и по часам окна получались бы разной длины.
    static constexpr double kWindowSeconds = 0.1;
};

// Счётчик того же самого для куска буфера целиком — для записи IQ, где отсчёты
// не разбираются по одному, а уходят в файл сырыми байтами. Разделяет с
// ClipMonitor порог и шкалу, чтобы «перегрузка при записи» и «перегрузка при
// просмотре этой записи» означали одно и то же число.
struct ClipScan {
    uint64_t clipped { 0 };
    uint64_t total   { 0 };
    int      peak    { 0 };

    // words — начало буфера, stride_words — сколько int16 на отсчёт (2 или 4).
    // В двухканальном режиме отсчёт считается зажатым, если зажат любой канал:
    // испорчен всё равно весь когерентный отсчёт.
    void scan(const int16_t* words, std::size_t n_samples, std::size_t stride_words);

    float clipped_pct() const {
        return total ? 100.0f * static_cast<float>(clipped) / static_cast<float>(total) : 0.0f;
    }
    float peak_dbfs() const;
};
